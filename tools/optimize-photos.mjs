// Compresses + resizes photos for fast mobile loading and writes
// assets/photos/manifest.js so the site shows however many you add.
//
//   1. Drop photos (any names, .jpg/.jpeg/.png/.webp/.heic*) into
//        assets/photos/now/   assets/photos/little/   assets/photos/funny/
//   2. cd tools && npm install   (first time only)
//   3. npm run photos
//
// Your originals are moved to photos-original/<folder>/ (kept out of git and
// out of the deploy), and the site gets 01.jpg, 02.jpg… in filename order.
// Want a different order? Rename the files in photos-original/ (e.g. 1-…, 2-…)
// and run it again — it always rebuilds from the originals.
//   * HEIC needs a sharp build with HEIF support; if it fails, AirDrop/export
//     as JPEG ("Most Compatible") instead.
import sharp from "sharp";
import { readdir, mkdir, rename, rm, writeFile, stat } from "node:fs/promises";
import { join, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FOLDERS = ["now", "little", "funny"];
const MAX = 1400;          // longest edge in px (crisp on a 3x iPhone at polaroid size)
const QUALITY = 78;
const IMG = /\.(jpe?g|png|webp|heic|heif|avif|tiff?)$/i;
const OUTPUT = /^\d{2,3}\.jpg$/;
const exists = (p) => stat(p).then(() => true, () => false);
const kb = (n) => (n / 1024).toFixed(0) + " KB";

const manifest = {};
for (const folder of FOLDERS) {
  const live = join(ROOT, "assets/photos", folder);
  const orig = join(ROOT, "photos-original", folder);
  await mkdir(live, { recursive: true });
  await mkdir(orig, { recursive: true });

  // move any newly dropped photos into the originals folder
  for (const f of await readdir(live)) {
    if (!IMG.test(f) || OUTPUT.test(f)) continue;
    let dest = join(orig, f), i = 1;
    while (await exists(dest)) dest = join(orig, f.replace(/(\.[^.]+)$/, `-${i++}$1`));
    await rename(join(live, f), dest);
  }
  // clear old outputs, rebuild everything from originals
  for (const f of await readdir(live)) if (OUTPUT.test(f)) await rm(join(live, f));
  const sources = (await readdir(orig)).filter((f) => IMG.test(f))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));

  manifest[folder] = [];
  let n = 0;
  for (const f of sources) {
    const name = String(++n).padStart(2, "0") + ".jpg";
    try {
      const info = await sharp(join(orig, f), { failOn: "none" })
        .rotate()                                   // respect iPhone orientation
        .resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true })
        .jpeg({ quality: QUALITY, mozjpeg: true, progressive: true })
        .withMetadata({ orientation: undefined })
        .toFile(join(live, name));
      manifest[folder].push({ src: `assets/photos/${folder}/${name}`, w: info.width, h: info.height });
      const before = (await stat(join(orig, f))).size;
      console.log(`  ${folder}/${name}  ←  ${f}   ${kb(before)} → ${kb(info.size)}`);
    } catch (e) {
      n--;
      console.warn(`  ! skipped ${f}: ${e.message}`);
    }
  }
}

await writeFile(join(ROOT, "assets/photos/manifest.js"),
  "/* AUTO-GENERATED by `npm run photos` (tools/optimize-photos.mjs). Don't edit by hand. */\n" +
  "window.PHOTOS = " + JSON.stringify(manifest, null, 2) + ";\n");

// friendly check against the captions in content.js
const ctx = { window: {} };
const { readFile } = await import("node:fs/promises");
new Function("window", await readFile(join(ROOT, "js/content.js"), "utf8"))(ctx.window);
const C = ctx.window.CONTENT;
const caps = { now: C.now.captions, little: C.little.captions, funny: C.bloopers.captions };
console.log("\nSummary");
for (const f of FOLDERS) {
  const p = manifest[f].length, c = caps[f].length;
  const note = p === c ? "✓" : p > c ? `(${p - c} photo(s) without a caption — add more in content.js)` : `(${c - p} extra caption(s) — they're ignored until you add photos)`;
  console.log(`  ${f.padEnd(7)} ${String(p).padStart(2)} photos, ${String(c).padStart(2)} captions  ${note}`);
}

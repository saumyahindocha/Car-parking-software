def pick_lang(query: Optional[str], cookie: Optional[str], accept: Optional[str]) -> str:
    for cand in (query, cookie):
        if cand in LANGS:
            return cand
    for part in (accept or "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in LANGS:
            return code
    return DEFAULT


def translate(lang: str, key: str, **kw) -> str:
    s = STRINGS.get(lang, {}).get(key) or STRINGS[DEFAULT].get(key) or key
    return s.format(**kw) if kw else s
